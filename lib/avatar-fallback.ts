export const guessGender = (name: string): "male" | "female" => {
  if (!name) {
    return "male";
  }
  const [first] = name
    .trim()
    .toLowerCase()
    .split(/[\s._-]/);
  if (!first) {
    return "male";
  }
  if (FEMALE_NAMES.has(first)) {
    return "female";
  }
  if (MALE_NAMES.has(first)) {
    return "male";
  }
  return "male";
};

export const getFallbackAvatar = (name: string): string =>
  guessGender(name) === "female"
    ? "/avatars/female-l-1.avif"
    : "/avatars/male-l.avif";
